/**
 * serverText.js — render-time localization for text produced by the backend.
 *
 * Why this module exists
 * ----------------------
 * The console language is a per-browser choice (App.vue persists it in
 * localStorage under `lang`). The backend never learns it, so any sentence the
 * server renders itself is frozen in one language and shows up as mixed
 * language in the other locale — e.g. the AI predictive maintenance alarm used
 * to store "AI predictive maintenance: <point>" and rendered in English inside
 * the Chinese console.
 *
 * Server-side producers now emit *bilingual* copy (core.BilingualText in
 * noyo/backend/core/i18n_text.go) and the client picks a language here. Rows
 * written before that contract keep a single-language string, so a small legacy
 * table below re-renders the ones the platform itself generated.
 *
 * Contract
 * --------
 * - `{"zh": "...", "en": "..."}` (object or JSON string) → the side matching
 *   the active locale, falling back to the other side, then to the raw value.
 * - A plain string → the legacy table is consulted, otherwise it is returned
 *   verbatim. Operator-authored text (rule names, work-order titles typed by a
 *   person, product/point names) must always pass through untouched.
 */

const isObjectPayload = (value) => Boolean(value) && typeof value === 'object' && !Array.isArray(value)

/** Maps any locale tag (zh-CN, en-US, …) onto the two supported locales. */
export const normalizeTextLocale = (locale) => (
  String(locale ?? '').toLowerCase().startsWith('en') ? 'en' : 'zh'
)

const pickLocalizedSide = (payload, locale) => {
  const lang = normalizeTextLocale(locale)
  const preferred = payload[lang]
  const fallback = payload[lang === 'en' ? 'zh' : 'en']
  const value = typeof preferred === 'string' && preferred.trim() ? preferred : fallback
  return typeof value === 'string' && value.trim() ? value : ''
}

/**
 * Detects a bilingual payload without resolving it. Useful when a caller needs
 * to strip the payload before pushing the value into an editable form field.
 */
export const isBilingualPayload = (value) => {
  if (isObjectPayload(value)) return pickLocalizedSide(value, 'zh') !== ''
  if (typeof value !== 'string') return false
  const text = value.trim()
  if (!text.startsWith('{') || !text.includes('"')) return false
  try {
    const parsed = JSON.parse(text)
    return isObjectPayload(parsed) && (pickLocalizedSide(parsed, 'zh') !== '' || pickLocalizedSide(parsed, 'en') !== '')
  } catch (_) {
    return false
  }
}

/**
 * Localized rendering rules for copy generated by the platform *before* the
 * bilingual contract existed. Each rule owns both languages, so it can repair
 * a historical row in either direction. Keep the list narrow: it must never
 * rewrite text an operator typed.
 */
const LEGACY_RULES = [
  {
    pattern: /^AI predictive maintenance recovered:\s*(.+)$/i,
    zh: (match) => `AI 预测维护异常已恢复：${match[1]}`,
    en: (match) => `AI predictive maintenance recovered: ${match[1]}`,
  },
  {
    pattern: /^AI predictive maintenance:\s*(.+)$/i,
    zh: (match) => `AI 预测维护异常：${match[1]}`,
    en: (match) => `AI predictive maintenance: ${match[1]}`,
  },
  {
    pattern: /^Automatically created from alarm\s+(.+)$/i,
    zh: (match) => `由告警自动创建：${match[1]}`,
    en: (match) => `Automatically created from alarm ${match[1]}`,
  },
  {
    pattern: /^(Work order transferred to you)$/i,
    zh: () => '工单已转派给你',
    en: () => 'Work order transferred to you',
  },
  {
    pattern: /^(Work order copied to you|工单抄送)$/,
    zh: () => '工单抄送',
    en: () => 'Work order copied to you',
  },
  {
    pattern: /^(New work order task)$/i,
    zh: () => '新的工单任务',
    en: () => 'New work order task',
  },
  {
    pattern: /^(Work order approval required)$/i,
    zh: () => '工单待审批',
    en: () => 'Work order approval required',
  },
  {
    pattern: /^(Automatically copied from a workflow node|来自流程节点自动抄送)$/,
    zh: () => '来自流程节点自动抄送',
    en: () => 'Automatically copied from a workflow node',
  },
  {
    pattern: /^(Passage obstruction|消防通道阻塞物)$/,
    zh: () => '消防通道阻塞物',
    en: () => 'Passage obstruction',
  },
  {
    pattern: /^(Passage obstruction cleared|消防通道阻塞已消除)$/,
    zh: () => '消防通道阻塞已消除',
    en: () => 'Passage obstruction cleared',
  },
]

const applyLegacyRule = (text, locale) => {
  const lang = normalizeTextLocale(locale)
  for (const rule of LEGACY_RULES) {
    const match = text.match(rule.pattern)
    if (match) return rule[lang](match)
  }
  return ''
}

/**
 * Resolves a value that came from the server into display text for `locale`.
 *
 * @param {unknown} value  Bilingual payload, JSON payload, plain string or null.
 * @param {string} locale  Active console locale (`zh` | `en` | any `en-*` tag).
 * @param {{ legacy?: boolean }} [options]  Set `legacy: false` to skip the
 *   legacy rewrite table when the value is known to be operator-authored.
 * @returns {string}
 */
export const resolveServerText = (value, locale, options = {}) => {
  if (value === null || value === undefined) return ''
  if (isObjectPayload(value)) return pickLocalizedSide(value, locale)

  const text = String(value)
  const trimmed = text.trim()
  if (!trimmed) return ''

  if (isBilingualPayload(trimmed)) {
    const parsed = JSON.parse(trimmed)
    return pickLocalizedSide(parsed, locale) || trimmed
  }

  // Callers that know the value was typed by an operator can pass
  // `{ legacy: false }` to keep it byte-identical.
  if (options.legacy !== false) {
    const rewritten = applyLegacyRule(trimmed, locale)
    if (rewritten) return rewritten
  }
  return text
}
