// Generate CSS from the shared token registry; --check verifies the checked-in output.
const fs = require('node:fs')
const path = require('node:path')
const directory = path.resolve(__dirname, '../app/src/noyo')
const tokens = require(path.join(directory, 'screenTokens.json'))
const target = path.join(directory, 'screenTokens.css')
const css = '/* Generated by tooling/screen-tokens.cjs from screenTokens.json. */\n:root{\n' +
  Object.entries(tokens).map(([name, value]) => `  ${name}:${value};`).join('\n') + '\n}\n'
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== css) throw new Error('Screen tokens CSS is stale; run node tooling/screen-tokens.cjs from integrations/goview.')
  console.log('Screen token CSS matches the shared registry')
} else {
  fs.writeFileSync(target, css)
}
